/*
 * Banco de demonstração do legacy-bridge.
 * Schema e dados 100% fictícios: não representam nenhum ERP ou empresa real.
 *
 * Executado pela imagem firebirdsql/firebird na primeira inicialização
 * (/docker-entrypoint-initdb.d), via isql conectado em FIREBIRD_DATABASE
 * como FIREBIRD_USER. Por isso não há CREATE DATABASE nem CONNECT aqui.
 */

SET SQL DIALECT 3;

/* ---------------------------------------------------------------------- */
/* Tabelas do "ERP"                                                       */
/* ---------------------------------------------------------------------- */

CREATE TABLE CLIENTES (
    ID            INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOME          VARCHAR(120) NOT NULL,
    DOCUMENTO     VARCHAR(20),
    EMAIL         VARCHAR(120),
    ATUALIZADO_EM TIMESTAMP,
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID)
);

CREATE TABLE PRODUTOS (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODIGO    VARCHAR(20) NOT NULL,
    DESCRICAO VARCHAR(120) NOT NULL,
    PRECO     NUMERIC(12,2) DEFAULT 0 NOT NULL,
    ESTOQUE   INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PRODUTOS PRIMARY KEY (ID)
);

CREATE TABLE PEDIDOS (
    ID         INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CLIENTE_ID INTEGER NOT NULL,
    DATA       TIMESTAMP NOT NULL,
    STATUS     VARCHAR(20) NOT NULL,
    TOTAL      NUMERIC(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
    CONSTRAINT FK_PEDIDOS_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES (ID)
);

/* ---------------------------------------------------------------------- */
/* Changelog lido pelo bridge                                             */
/* ---------------------------------------------------------------------- */

CREATE SEQUENCE SEQ_BRIDGE_CHANGELOG;

CREATE TABLE BRIDGE_CHANGELOG (
    ID          BIGINT NOT NULL,
    TABELA      VARCHAR(31) NOT NULL,
    REGISTRO_ID INTEGER NOT NULL,
    OPERACAO    CHAR(1) NOT NULL,
    CRIADO_EM   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_BRIDGE_CHANGELOG PRIMARY KEY (ID),
    CONSTRAINT CK_BRIDGE_CHANGELOG_OP CHECK (OPERACAO IN ('I', 'U', 'D'))
);

SET TERM ^ ;

CREATE TRIGGER TRG_BRIDGE_CHANGELOG_BI FOR BRIDGE_CHANGELOG
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN
        NEW.ID = NEXT VALUE FOR SEQ_BRIDGE_CHANGELOG;
END^

/* Uma trigger por tabela cobrindo os três eventos. */

CREATE TRIGGER TRG_CLIENTES_BRIDGE FOR CLIENTES
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 100
AS
BEGIN
    IF (INSERTING) THEN
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('CLIENTES', NEW.ID, 'I');
    ELSE IF (UPDATING) THEN
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('CLIENTES', NEW.ID, 'U');
    ELSE
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('CLIENTES', OLD.ID, 'D');
END^

CREATE TRIGGER TRG_PRODUTOS_BRIDGE FOR PRODUTOS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 100
AS
BEGIN
    IF (INSERTING) THEN
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('PRODUTOS', NEW.ID, 'I');
    ELSE IF (UPDATING) THEN
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('PRODUTOS', NEW.ID, 'U');
    ELSE
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('PRODUTOS', OLD.ID, 'D');
END^

CREATE TRIGGER TRG_PEDIDOS_BRIDGE FOR PEDIDOS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 100
AS
BEGIN
    IF (INSERTING) THEN
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('PEDIDOS', NEW.ID, 'I');
    ELSE IF (UPDATING) THEN
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('PEDIDOS', NEW.ID, 'U');
    ELSE
        INSERT INTO BRIDGE_CHANGELOG (TABELA, REGISTRO_ID, OPERACAO) VALUES ('PEDIDOS', OLD.ID, 'D');
END^

SET TERM ; ^

COMMIT;

